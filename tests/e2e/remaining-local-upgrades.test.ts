import { _electron as electron, expect, test } from '@playwright/test';
import { copyFileSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import type { SuperLibraryApi } from '../../src/shared/library-api';
import { assetCard, resolveElectronExecutablePath } from './electron-test-helpers';

test('real workspaces retain filters and previews; fonts, GIF controls and partial batch folders work', async () => {
  test.setTimeout(150_000);
  const root=mkdtempSync(path.join(tmpdir(),'super-remaining-e2e-'));
  const image=path.join(root,'Picture.png'), font=path.join(root,'Sample.ttf'), gif=path.join(root,'Animated.gif'), text=path.join(root,'Legacy.txt');
  writeFileSync(image,await sharp({create:{width:3840,height:2160,channels:3,background:'#487fe5'}}).png().toBuffer());
  copyFileSync(path.resolve('resources/fonts/DejaVuSans.ttf'),font);
  const pixels=Buffer.alloc(32*32*3*2); pixels.fill(255,0,32*32*3); pixels.fill(64,32*32*3);
  writeFileSync(gif,await sharp(pixels,{raw:{width:32,height:64,channels:3,pageHeight:32}}).gif({delay:[100,100],loop:0}).toBuffer());
  writeFileSync(text,Buffer.from([0xff,0xfe,0x60,0x4f,0x7d,0x59]));
  const sources=[image,font,gif,text];
  const app=await electron.launch({executablePath:resolveElectronExecutablePath(),args:[process.cwd()],env:{...process.env,SUPER_E2E:'1',SUPER_E2E_CREATE_PARENT_PATH:root,SUPER_E2E_USER_DATA_PATH:path.join(root,'profile'),SUPER_E2E_IMPORT_FILES:sources.join(path.delimiter)}});
  try {
    const page=await app.firstWindow();
    page.on('console', message => {if (message.text().includes('GIF frame preview unavailable')) process.stdout.write(message.text()+'\n');});
    await page.getByRole('button',{name:'跳过引导',exact:true}).click();
    await page.getByRole('button',{name:'创建资源库',exact:true}).click();
    await page.getByRole('textbox',{name:'名称',exact:true}).fill('Remaining upgrades');
    await page.getByRole('button',{name:'创建',exact:true}).click();
    await page.getByRole('button',{name:'导入文件',exact:true}).first().click();
    await expect(assetCard(page,'Picture.png')).toBeVisible({timeout:30000});
    const search=page.locator('.toolbar-workspace-search input[type="search"]');
    await search.fill('Picture');
    await expect(assetCard(page,'Sample.ttf')).toHaveCount(0);
    await expect.poll(()=>page.locator('#super-search-history option').count()).toBe(1);
    await page.getByRole('button',{name:'新工作区',exact:true}).click();
    await expect(page.getByRole('tab',{name:'工作区 2',exact:true})).toHaveAttribute('aria-selected','true');
    await expect(search).toHaveValue('');
    await expect(assetCard(page,'Sample.ttf')).toBeVisible();
    await assetCard(page,'Sample.ttf').click(); await page.keyboard.press('Space');
    await expect(page.locator('.font-viewer-sample')).toBeVisible({timeout:15000});
    await expect.poll(()=>page.evaluate(()=>[...document.fonts].filter(f=>f.family.startsWith('super-font-')).length)).toBe(1);
    await page.screenshot({path:test.info().outputPath('font-preview.png')});
    await page.keyboard.press('Escape');
    await expect.poll(()=>page.evaluate(()=>[...document.fonts].filter(f=>f.family.startsWith('super-font-')).length)).toBe(0);
    await assetCard(page,'Animated.gif').click(); await page.keyboard.press('Space');
    await expect(page.locator('.gif-viewer-controls')).toBeVisible({timeout:15000});
    await page.locator('.gif-viewer-controls button').first().click();
    await expect(page.locator('.gif-viewer-controls button').first()).toHaveAttribute('aria-label','播放');
    await page.locator('.gif-viewer-controls input').focus(); await page.keyboard.press('Home');
    await page.getByRole('button',{name:'下一帧',exact:true}).click();
    await expect.poll(()=>page.locator('.gif-viewer-controls input').inputValue()).toBe('1');
    await page.screenshot({path:test.info().outputPath('gif-controls.png')});
    await page.keyboard.press('Escape');
    await page.getByRole('tab',{name:'工作区 1',exact:true}).click();
    await expect(search).toHaveValue('Picture');
    await expect(assetCard(page,'Sample.ttf')).toHaveCount(0);
    await assetCard(page,'Picture.png').click(); await page.keyboard.press('Space');
    await expect(page.locator('img[src^="super://source/"]')).toBeVisible({timeout:15000});
    const originalImage=page.locator('img[src^="super://source/"]');
    const beforeZoom=await originalImage.evaluate(image=>image.getBoundingClientRect().width);
    await page.locator('.preview-image-viewport').hover(); await page.mouse.wheel(0,-220);
    await expect.poll(()=>originalImage.evaluate(image=>image.getBoundingClientRect().width)).toBeGreaterThan(beforeZoom);
    const savedWidth=await originalImage.evaluate(image=>image.getBoundingClientRect().width);
    await page.getByRole('button',{name:'新工作区',exact:true}).click();
    await expect(page.getByRole('tab',{name:'工作区 3',exact:true})).toHaveAttribute('aria-selected','true');
    await expect(page.locator('[aria-label="Picture.png 查看页面"]')).toHaveCount(0);
    await page.getByRole('tab',{name:'工作区 1',exact:true}).click();
    await expect(page.getByRole('region',{name:'Picture.png 查看页面',exact:true})).toBeVisible();
    await expect.poll(async()=>Math.abs(await originalImage.evaluate(image=>image.getBoundingClientRect().width)-savedWidth)).toBeLessThan(1);
    await page.screenshot({path:test.info().outputPath('workspace-preview.png')});
    await page.keyboard.press('Escape');
    await page.getByRole('tab',{name:'工作区 2',exact:true}).click();
    await page.getByRole('button',{name:'批量新建文件夹…',exact:true}).click();
    await page.locator('.batch-folders-dialog textarea').fill('Batch one\nCON\nBatch two');
    await page.locator('.batch-folders-dialog .primary-button').click();
    await expect(page.locator('.batch-folders-dialog li')).toHaveCount(3);
    const folders=await page.evaluate(async()=>{const api=(globalThis as typeof globalThis & {super:{library:SuperLibraryApi}}).super.library;const libs=await api.listOpen();if(!libs.ok)throw Error('Library');return api.listFolders({libraryId:libs.value[0]!.libraryId});});
    expect(folders.ok && folders.value.filter(f=>f.name.startsWith('Batch')).length).toBe(2);
    await page.screenshot({path:test.info().outputPath('remaining-batch.png')});
    await page.locator('.batch-folders-dialog').getByRole('button',{name:'关闭',exact:true}).click();
    const sidebarSearch = page.getByRole('searchbox',{name:'筛选文件夹与合集',exact:true});
    await sidebarSearch.fill('Batch one');
    await page.getByRole('combobox',{name:'侧栏排序',exact:true}).selectOption('name-asc');
    await expect(page.locator('.navigation-pane .nav-row-label', {hasText:'Batch one'})).toBeVisible();
    await expect(page.locator('.navigation-pane .nav-row-label', {hasText:'Batch two'})).toHaveCount(0);
    await page.locator('.navigation-pane .nav-row-label', {hasText:'Batch one'}).click();
    await expect(page.locator('.folder-inspector .metadata-list')).toBeVisible();
    await page.screenshot({path:test.info().outputPath('folder-sidebar.png')});
    await sidebarSearch.fill('');
    await page.getByRole('button',{name:'所有资产',exact:false}).first().click();
    await assetCard(page,'Legacy.txt').click(); await page.keyboard.press('Space');
    await expect(page.locator('.preview-text-topbar')).toContainText('UTF-16LE');
    await page.getByRole('button',{name:'自动折行',exact:true}).click();
    await expect(page.locator('.preview-text-scroll')).toHaveClass(/is-wrapped/);
    await page.screenshot({path:test.info().outputPath('text-wrap.png')});
    await page.keyboard.press('Escape');
    const colorButton = page.locator('.dimension-filter-dim[data-dimension="color"] > button');
    await colorButton.hover(); await colorButton.focus();
    const custom = page.getByLabel('自定义颜色',{exact:true});
    await expect(custom).toBeVisible();
    await custom.evaluate(input => {
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value')!.set!.call(input,'#335577');
      input.dispatchEvent(new Event('input',{bubbles:true}));
      input.dispatchEvent(new Event('change',{bubbles:true}));
    });
    await expect(page.getByRole('slider',{name:'颜色容差（HSL）',exact:true})).toBeVisible();
    await page.screenshot({path:test.info().outputPath('custom-color.png')});
  } catch(error) {await (await app.firstWindow()).screenshot({path:test.info().outputPath('remaining-failure.png')});throw error;} finally {await app.close();}
});
